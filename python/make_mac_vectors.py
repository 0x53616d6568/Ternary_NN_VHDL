"""Generate the data files tb_TernaryMacEngine.vhd reads.

The MAC-engine testbench loads its weights and biases from disk rather than
instantiating ModelWeights, so that the engine can be tested in isolation from
the exported VHDL package. That means it needs two files:

    w1_packed.txt   N_INPUTS lines, one hex word per line, N_HIDDEN*2 bits each
                    (two bits per ternary weight, same packing as
                     W1_PACKED_INIT, but transposed: one line per *input*)

    b1.txt          N_HIDDEN lines, one hex value per line, ACC_WIDTH bits each

These files were generated by a script that no longer existed in the
repository, which meant tb_TernaryMacEngine could not run at all. This
regenerates them from the exported parameter file, so the packing is taken from
the same array the exporter wrote into the VHDL rather than being re-derived
here -- if the two ever disagreed, the test would be testing the wrong thing.

Usage:
    python make_mac_vectors.py model/mnist_h32aug.pt
"""
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))


def main():
    checkpoint = sys.argv[1] if len(sys.argv) > 1 else "model/mnist_h32aug.pt"
    parameters = sys.argv[2] if len(sys.argv) > 2 else "output/vhdl_parameters.npz"

    arrays = np.load(parameters)
    packed = np.asarray(arrays["W1_PACKED"])
    bias = np.asarray(arrays["B1"])
    w1 = np.asarray(arrays["W1"])

    # W1 is stored hidden-major, i.e. shape (n_hidden, n_inputs).
    n_hidden, n_inputs = w1.shape
    acc_width = 32  # matches ACC_WIDTH in NumberRecognition.vhd

    if packed.shape[0] != n_inputs:
        raise SystemExit(f"W1_PACKED has {packed.shape[0]} words but W1 has "
                         f"{n_inputs} inputs")

    print(f"W1 {w1.shape} -> {n_inputs} inputs x {n_hidden} hidden")
    print(f"ACC_WIDTH {acc_width}, bias {bias.shape}")

    # One hex word per input. W1_PACKED is already the exact packing the
    # exporter wrote into W1_PACKED_INIT, so it is emitted verbatim rather than
    # re-derived -- re-packing here would risk testing a different layout from
    # the one the hardware uses.
    with open("w1_packed.txt", "w", newline="\n") as f:
        for word in packed:
            f.write(f"{int(word):016x}\n")

    # One hex bias per hidden unit, low-order unit first, matching the slice
    # order the testbench uses.
    with open("b1.txt", "w", newline="\n") as f:
        for h in range(n_hidden):
            value = int(bias[h]) & ((1 << acc_width) - 1)
            f.write(f"{value:0{acc_width // 4}x}\n")

    print(f"wrote w1_packed.txt ({n_inputs} lines) and b1.txt ({n_hidden} lines)")


if __name__ == "__main__":
    main()
